-- List helpers (keep the long component lists short and readable)
--   seq('COMPONENT_X_', 1, 10) -> { 'COMPONENT_X_1', ..., 'COMPONENT_X_10' }
--   join(a, b, ...)            -> a followed by b followed by ...
local function seq(prefix, from, to)
    local list = {}
    for i = from, to do list[#list + 1] = prefix .. i end
    return list
end

local function join(...)
    local list = {}
    for _, part in ipairs({ ... }) do
        for _, v in ipairs(part) do list[#list + 1] = v end
    end
    return list
end

